"""Write SAMPLE_QA.md: real answers from the app pipeline for the brief's example queries.

The brief asks for "5-10 queries with the assistant's answers + links". These are generated by running
the actual Assistant (the same code the UI calls), so the file shows genuine behaviour, not
hand-written answers.

Run:  python -m mf_assistant.evaluation.sample_qa
"""

from datetime import date

from mf_assistant import config
from mf_assistant.answer.pipeline import Assistant

# The brief's example topics, plus a refusal and a privacy case
QUESTIONS = [
    "What is the expense ratio of the Parag Parikh Flexi Cap fund?",
    "What is the lock-in period of the PPFAS ELSS Tax Saver fund?",
    "What is the minimum SIP amount for the Parag Parikh Liquid fund?",
    "What is the exit load of the Parag Parikh Arbitrage fund?",
    "What are the riskometer and benchmark of the PPFAS Conservative Hybrid fund?",
    "How do I download my Consolidated Account Statement (CAS)?",
    "What is the exit load of the ELSS fund and how do I download my CAS?",
    "Should I invest in the Flexi Cap fund for long-term wealth?",
    "My PAN is ABCDE1234F, which funds do I hold?",
]

PATH = config.REPO_ROOT / "SAMPLE_QA.md"


def main():
    assistant = Assistant()
    blocks = []
    for i, q in enumerate(QUESTIONS, 1):
        r = assistant.ask(q)
        shown_q = "My PAN is [redacted example], which funds do I hold?" if r.handler == "pii" else q
        answer = r.answer.text.replace("\n", "  \n")  # markdown line breaks
        blocks.append(f"### {i}. {shown_q}\n\n*Handled by: `{r.handler}`*\n\n{answer}\n")
        print(f"{i}. [{r.handler}] {q}")
    PATH.write_text(
        f"# Sample Q&A\n\nGenerated on {date.today()} by running the app pipeline "
        f"(`python -m mf_assistant.evaluation.sample_qa`). Answers, sources and dates are exactly what "
        f"the assistant returned.\n\n> {config.DISCLAIMER_LONG}\n\n" + "\n".join(blocks), encoding="utf-8")
    print(f"→ {PATH}")


if __name__ == "__main__":
    main()
